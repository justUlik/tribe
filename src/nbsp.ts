const HANG = [
  'вместо',
  'кроме',
  'между',
  'перед',
  'около',
  'через',
  'либо',
  'или',
  'для',
  'при',
  'без',
  'над',
  'под',
  'про',
  'из',
  'изо',
  'во',
  'ко',
  'со',
  'об',
  'от',
  'до',
  'на',
  'за',
  'по',
  'к',
  'в',
  'с',
  'у',
  'о',
  'и',
  'а',
  'но',
  'да',
  'ни',
  'не',
  'же',
  'бы',
  'ли',
  'что',
  'как',
  'то',
  'все',
  'вы',
];

export function nbspText(text: string) {
  const hang = new RegExp(`(^|[^\\p{L}\\p{N}])(${HANG.join('|')}) `, 'giu');
  return text.replace(hang, '$1$2\u00A0').replace(/(\d) (\p{L})/gu, '$1\u00A0$2');
}
